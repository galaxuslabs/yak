import tsParser from "@typescript-eslint/parser";
import { RuleTester } from "@typescript-eslint/rule-tester";
import * as vitest from "vitest";
import yakPlugin from "../index.js";

RuleTester.afterAll = vitest.afterAll;
RuleTester.it = vitest.it;
RuleTester.itOnly = vitest.it.only;
RuleTester.describe = vitest.describe;

const ruleTester = new RuleTester({ languageOptions: { parser: tsParser } });
const rule = yakPlugin.rules["styled-arrow-function-statements"] as unknown as Parameters<
  typeof ruleTester.run
>[1];

const react = 'import { css, styled } from "@yak/react";';
const code = (...lines: string[]) => [react, ...lines].join("\n");

ruleTester.run("yak-styled-arrow-function-statements", rule, {
  valid: [
    {
      name: "an expression",
      code: code("styled.div`", "  ${({ $on }) => $on && css`color: red;`}", "`;"),
    },
    {
      name: "a single return",
      code: code(
        "styled.div`",
        "  ${({ $on }) => {",
        "    return $on && css`color: red;`;",
        "  }}",
        "`;",
      ),
    },
    {
      name: "an if without else",
      code: code(
        "styled.div`",
        "  ${({ $on }) => {",
        "    if ($on) {",
        "      return css`color: red;`;",
        "    }",
        "  }}",
        "`;",
      ),
    },
    {
      name: "early returns",
      code: code(
        "styled.div`",
        "  ${({ $size }) => {",
        '    if ($size === "s") return css`padding: 1px;`;',
        '    if ($size === "m") return css`padding: 2px;`;',
        "    return css`padding: 3px;`;",
        "  }}",
        "`;",
      ),
    },
    {
      name: "if and else",
      code: code(
        "styled.div`",
        "  ${({ $on }) => {",
        "    if ($on) {",
        "      return css`color: red;`;",
        "    } else {",
        "      return css`color: blue;`;",
        "    }",
        "  }}",
        "`;",
      ),
    },
    {
      name: "a nested if that ends the function",
      code: code(
        "styled.div`",
        "  ${({ $on, $big }) => {",
        "    if ($on) {",
        "      if ($big) return css`color: red;`;",
        "    }",
        "  }}",
        "`;",
      ),
    },
    {
      name: "an if branch without return and a single return after it",
      code: code(
        "styled.div`",
        "  ${({ $on, $big }) => {",
        "    if ($on) {",
        "      if ($big) return css`color: red;`;",
        "    } else {",
        "      if ($big) return css`color: green;`;",
        "    }",
        "    return css`color: blue;`;",
        "  }}",
        "`;",
      ),
    },
    {
      name: "a switch with default",
      code: code(
        "styled.div`",
        "  ${({ $variant }) => {",
        "    switch ($variant) {",
        '      case "primary":',
        "        return css`color: blue;`;",
        '      case "danger": {',
        "        return css`color: red;`;",
        "      }",
        "      default:",
        "        return css`color: gray;`;",
        "    }",
        "  }}",
        "`;",
      ),
    },
    {
      name: "a switch with an enum member and a constant as case values",
      code: code(
        "styled.div`",
        "  ${({ $animation }) => {",
        "    switch ($animation) {",
        "      case Animation.In:",
        "        return css`opacity: 1;`;",
        "      case OUT:",
        "        return css`opacity: 0;`;",
        "      default:",
        "        return;",
        "    }",
        "  }}",
        "`;",
      ),
    },
    {
      name: "a switch with grouped labels on a member read, followed by a return",
      code: code(
        "styled.div`",
        "  ${(props) => {",
        "    switch (props.$size!) {",
        '      case "s":',
        '      case "m":',
        "        return css`padding: 1px;`;",
        "      case 3:",
        "        return css`padding: 2px;`;",
        "    }",
        "    return css`padding: 3px;`;",
        "  }}",
        "`;",
      ),
    },
    {
      name: "a value with if and return",
      code: code(
        "styled.div`",
        "  left: ${({ $x }) => {",
        "    if ($x === undefined) return 0;",
        "    return $x;",
        "  }}px;",
        "`;",
      ),
    },
    {
      name: "a css literal",
      code: code(
        "css`",
        "  ${({ $on }) => {",
        "    if ($on) return css`color: red;`;",
        "  }}",
        "`;",
      ),
    },
    {
      name: "a function that is no part of a literal",
      code: code("const helper = () => {", "  console.log(1);", "};"),
    },
    {
      name: "@yak/solid keeps its own render path",
      code: [
        'import { css, styled } from "@yak/solid";',
        "styled.div`",
        "  ${({ $on }) => {",
        "    console.log($on);",
        "    return $on && css`color: red;`;",
        "  }}",
        "`;",
      ].join("\n"),
    },
    {
      name: "another library",
      code: [
        'import styled, { css } from "styled-components";',
        "styled.div`",
        "  ${({ $on }) => {",
        "    console.log($on);",
        "    return $on && css`color: red;`;",
        "  }}",
        "`;",
      ].join("\n"),
    },
  ],
  invalid: [
    {
      name: "a function call",
      code: code(
        "styled.div`",
        "  ${({ $on }) => {",
        "    console.log($on);",
        "    return $on && css`color: red;`;",
        "  }}",
        "`;",
      ),
      errors: [
        {
          messageId: "statement",
          data: { statement: "statement like a function call or an assignment" },
          line: 4,
        },
      ],
    },
    {
      name: "a debugger statement inside an if",
      code: code(
        "styled.div`",
        "  ${({ $on }) => {",
        "    if ($on) {",
        "      debugger;",
        "      return css`color: red;`;",
        "    }",
        "  }}",
        "`;",
      ),
      errors: [{ messageId: "statement", data: { statement: "`debugger` statement" }, line: 5 }],
    },
    {
      name: "a variable",
      code: code(
        "styled.div`",
        "  ${({ $size }) => {",
        "    const big = $size > 2;",
        "    return big && css`color: red;`;",
        "  }}",
        "`;",
      ),
      errors: [{ messageId: "statement", data: { statement: "variable declaration" }, line: 4 }],
    },
    {
      name: "a loop and a try statement",
      code: code(
        "styled.div`",
        "  ${({ $list }) => {",
        "    for (const item of $list) {",
        "      if (item) return css`color: red;`;",
        "    }",
        "    try {",
        "      return css`color: blue;`;",
        "    } catch {}",
        "  }}",
        "`;",
      ),
      errors: [
        { messageId: "statement", data: { statement: "loop" }, line: 4 },
        { messageId: "statement", data: { statement: "`try` statement" }, line: 7 },
      ],
    },
    {
      name: "a statement in a value",
      code: code(
        "styled.div`",
        "  left: ${({ $x }) => {",
        "    const x = $x * 2;",
        "    return x;",
        "  }}px;",
        "`;",
      ),
      errors: [{ messageId: "statement", line: 4 }],
    },
    {
      name: "a statement in a nested css literal",
      code: code(
        "styled.div`",
        "  ${({ $on }) =>",
        "    $on &&",
        "    css`",
        "      color: ${({ $color }) => {",
        "        console.log($color);",
        "        return $color;",
        "      }};",
        "    `}",
        "`;",
      ),
      errors: [{ messageId: "statement", line: 7 }],
    },
    {
      name: "a function expression",
      code: code(
        "styled.div`",
        "  ${function ({ $on }) {",
        "    return $on && css`color: red;`;",
        "  }}",
        "`;",
      ),
      errors: [{ messageId: "functionExpression", line: 3 }],
    },
    {
      name: "an if branch without return and statements after it",
      code: code(
        "styled.div`",
        "  ${({ $on, $big }) => {",
        "    if ($on) {",
        "      if ($big) return css`color: red;`;",
        "    }",
        "    if ($big) return css`color: green;`;",
        "    return css`color: blue;`;",
        "  }}",
        "`;",
      ),
      errors: [{ messageId: "branchWithoutReturn", data: { statement: "`if` branch" }, line: 4 }],
    },
    {
      name: "an else branch without return and statements after it",
      code: code(
        "styled.div`",
        "  ${({ $on, $big }) => {",
        "    if ($on) {",
        "      return css`color: red;`;",
        "    } else {",
        "      if ($big) return css`color: green;`;",
        "    }",
        "    if ($big) return css`color: yellow;`;",
        "    return css`color: blue;`;",
        "  }}",
        "`;",
      ),
      errors: [{ messageId: "branchWithoutReturn", data: { statement: "`else` branch" }, line: 6 }],
    },
    {
      name: "a switch on a call",
      code: code(
        "styled.div`",
        "  ${({ $on }) => {",
        "    switch (String($on)) {",
        '      case "true":',
        "        return css`color: red;`;",
        "    }",
        "  }}",
        "`;",
      ),
      errors: [{ messageId: "switchDiscriminant", line: 4 }],
    },
    {
      name: "a case that is a call",
      code: code(
        "styled.div`",
        "  ${({ $size }) => {",
        "    switch ($size) {",
        "      case small():",
        "        return css`color: red;`;",
        "    }",
        "  }}",
        "`;",
      ),
      errors: [{ messageId: "switchCaseTest", line: 5 }],
    },
    {
      name: "a case with break",
      code: code(
        "styled.div`",
        "  ${({ $size }) => {",
        "    switch ($size) {",
        '      case "s":',
        "        break;",
        '      case "m":',
        "        return css`color: red;`;",
        "    }",
        "    return css`color: blue;`;",
        "  }}",
        "`;",
      ),
      errors: [{ messageId: "switchCaseWithoutReturn", line: 5 }],
    },
    {
      name: "a case that runs into the next one",
      code: code(
        "styled.div`",
        "  ${({ $size, $on }) => {",
        "    switch ($size) {",
        '      case "s":',
        "        if ($on) return css`color: red;`;",
        '      case "m":',
        "        return css`color: blue;`;",
        "    }",
        "  }}",
        "`;",
      ),
      errors: [{ messageId: "switchCaseWithoutReturn", line: 5 }],
    },
    {
      name: "a default case that is not the last one",
      code: code(
        "styled.div`",
        "  ${({ $size }) => {",
        "    switch ($size) {",
        "      default:",
        "        return css`color: red;`;",
        '      case "m":',
        "        return css`color: blue;`;",
        "    }",
        "  }}",
        "`;",
      ),
      errors: [{ messageId: "switchDefaultNotLast", line: 5 }],
    },
  ],
});
